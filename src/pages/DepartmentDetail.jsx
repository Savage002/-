export default function DepartmentDetail() {
    const { id } = useParams();
    const { language } = useLanguage();
    const [dept, setDept] = useState(null);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState(false);

    useEffect(() => {
        let cancelled = false;
        fetch(`/api/departments/${id}`)
            .then(res => {
                if (!res.ok) throw new Error('Not found');
                return res.json();
            })
            .then(data => { if (!cancelled) { setDept(data); setLoading(false); } })
            .catch(() => { if (!cancelled) { setError(true); setLoading(false); } });
        return () => { cancelled = true; };
    }, [id]);

    const n = (item, field) => item?.[`${field}_${language}`] || item?.[`${field}_ru`] || '';

    if (loading) return <div className="dept-detail-loading"><div className="dept-spinner" /><p>{language === 'kk' ? 'Жүктелуде...' : 'Загрузка...'}</p></div>;
    if (error || !dept) return <DeptNotFound language={language} />;

    const meta = deptMeta[dept.id] || defaultMeta;
    const divisions = dept.divisions || [];
    const totalSectors = divisions.reduce((s, d) => s + (d.sectors?.length || 0), 0);

    const breadcrumbLabel = language === 'kk' ? 'Құрылым' : 'Структура';
    const directorLabel = n(dept, 'director_title') || (language === 'kk' ? 'Басшы' : 'Руководитель');
    const divisionsLabel = language === 'kk' ? 'Бөлімдер мен басқармалар' : 'Отделы и управления';
    const sectorsLabel = language === 'kk' ? 'Секторлар' : 'Секторы';
    const headLabel = language === 'kk' ? 'Басшы' : 'Руководитель';
    const backLabel = language === 'kk' ? '← Барлық бөлімшелер' : '← Все подразделения';

    return (
        <div className="dept-detail-page">

            {/* Hero */}
            <HeroSection
                dept={dept}
                meta={meta}
                n={n}
                breadcrumbLabel={breadcrumbLabel}
                directorLabel={directorLabel}
            />

            {/* Stats bar */}
            <StatsBar
                divisions={divisions}
                totalSectors={totalSectors}
                language={language}
            />

            {/* Content */}
            <div className="dept-detail-content">

                {/* Rich static content */}
                {DEPT_CONTENT[dept.name_ru] && (() => {
                    const unit = DEPT_CONTENT[dept.name_ru];
                    const content = unit[language] || unit.ru;
                    return <DeptContent content={content} meta={meta} />;
                })()}

                {/* Divisions */}
                {divisions.length > 0 && (
                    <section className="dept-divisions-section">
                        <SectionHeader label={divisionsLabel} />

                        <div className="dept-divisions-grid">
                            {divisions.map((div, idx) => (
                                <DivisionCard
                                    key={div.id}
                                    div={div}
                                    idx={idx}
                                    meta={meta}
                                    n={n}
                                    headLabel={headLabel}
                                    sectorsLabel={sectorsLabel}
                                />
                            ))}
                        </div>
                    </section>
                )}

                {/* Back link */}
                <div className="dept-back-wrap">
                    <Link to="/Structure" className="dept-back-link">{backLabel}</Link>
                </div>
            </div>
        </div>
    );
}

